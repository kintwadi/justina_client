import { Location } from '@angular/common';
import { ChangeDetectionStrategy, Component, computed, effect, inject, signal } from '@angular/core';
import { ActivatedRoute, Router } from '@angular/router';
import { Product, ProductVariant } from '../../core/models/product.model';
import { CartService } from '../../core/services/cart.service';
import { CatalogService } from '../../core/services/catalog.service';
import { LocaleService } from '../../core/services/locale.service';
import { ToastService } from '../../core/services/toast.service';
import { IconComponent } from '../../shared/components/icon/icon';

@Component({
  selector: 'app-product-detail-page',
  changeDetection: ChangeDetectionStrategy.OnPush,
  imports: [IconComponent],
  templateUrl: './product-detail.html',
  styleUrl: './product-detail.scss',
})
export class ProductDetailPageComponent {
  private readonly route = inject(ActivatedRoute);
  private readonly router = inject(Router);
  private readonly location = inject(Location);
  private readonly catalog = inject(CatalogService);
  private readonly cart = inject(CartService);
  private readonly toast = inject(ToastService);
  protected readonly locale = inject(LocaleService);

  private readonly productId = signal<number | null>(null);
  private readonly activeImageState = signal<string | null>(null);
  private readonly selectedVariantSkuState = signal<string | null>(null);
  protected readonly loading = signal(true);

  protected readonly allProducts = this.catalog.allProducts;
  protected readonly product = computed(() => {
    const id = this.productId();
    if (id === null) {
      return null;
    }
    return this.catalog.findById(id) ?? null;
  });
  protected readonly productIndex = computed(() => {
    const product = this.product();
    if (!product) {
      return -1;
    }
    return this.allProducts().findIndex((item) => item.id === product.id);
  });
  protected readonly previousProduct = computed(() => {
    const index = this.productIndex();
    return index > 0 ? this.allProducts()[index - 1] : null;
  });
  protected readonly nextProduct = computed(() => {
    const index = this.productIndex();
    return index >= 0 && index < this.allProducts().length - 1
      ? this.allProducts()[index + 1]
      : null;
  });
  protected readonly variants = computed(() => this.product()?.variants ?? []);
  protected readonly selectedVariant = computed(() => {
    const sku = this.selectedVariantSkuState();
    if (!sku) {
      return null;
    }
    return this.variants().find((variant) => variant.sku === sku) ?? null;
  });
  protected readonly galleryImages = computed(() => {
    const product = this.product();
    if (!product) {
      return [];
    }

    const variant = this.selectedVariant();
    const images = [
      variant?.image ?? product.image,
      ...(variant?.gallery?.length ? variant.gallery : product.gallery ?? []),
    ]
      .map((image) => image?.trim() ?? '')
      .filter((image): image is string => Boolean(image));
    return [...new Set(images)];
  });
  protected readonly activeImage = computed(
    () => this.activeImageState() ?? this.galleryImages()[0] ?? null,
  );
  protected readonly activePrice = computed(() => {
    const product = this.product();
    if (!product) {
      return 0;
    }
    const variant = this.selectedVariant();
    if (variant?.price !== null && variant?.price !== undefined && variant.price > 0) {
      return variant.price;
    }
    return product.price + (variant?.priceDelta ?? 0);
  });
  protected readonly activeOriginalPrice = computed(() => {
    const product = this.product();
    if (!product || product.originalPrice === null) {
      return null;
    }
    const variant = this.selectedVariant();
    if (
      variant?.price !== null &&
      variant?.price !== undefined &&
      variant.price > 0 &&
      variant.priceDelta !== null
    ) {
      return product.originalPrice + variant.priceDelta;
    }
    return product.originalPrice + (variant?.priceDelta ?? 0);
  });
  protected readonly variantDetailRows = computed(() => {
    const variant = this.selectedVariant();
    if (!variant) {
      const product = this.product();
      if (!product) {
        return [];
      }
      return [
        { label: this.locale.t('product.sku'), value: product.sku?.trim() || this.locale.t('product.autoGenerated') },
        {
          label: this.locale.t('product.stock'),
          value:
            product.stockQuantity && product.stockQuantity > 0
              ? `${product.stockQuantity} ${this.locale.t('product.available')}`
              : this.locale.t('product.soldOut'),
        },
        ...Object.entries(product.options ?? {}).map(([label, value]) => ({
          label: this.labelize(label),
          value,
        })),
      ];
    }

    const rows = [
      { label: this.locale.t('product.variant'), value: variant.name },
      { label: this.locale.t('product.sku'), value: variant.sku },
      {
        label: this.locale.t('product.stock'),
        value:
          variant.stock > 0
            ? `${variant.stock} ${this.locale.t('product.available')}`
            : this.locale.t('product.soldOut'),
      },
    ];

    for (const [label, value] of Object.entries(variant.options ?? {})) {
      rows.push({ label: this.labelize(label), value });
    }

    if (!Object.keys(variant.options ?? {}).length) {
      rows.push({ label: this.locale.t('product.size'), value: variant.name });
    }

    return rows;
  });
  protected readonly canAddToBag = computed(() => {
    if (this.product()?.customMade) {
      return false;
    }
    const product = this.product();
    if (!product?.inStock) {
      return false;
    }
    const variant = this.selectedVariant();
    return variant ? variant.stock > 0 : (product.stockQuantity ?? 0) > 0;
  });
  protected readonly addToBagLabel = computed(() => {
    if (this.product()?.customMade) {
      return this.locale.t('product.requestCustomOrder');
    }
    if (this.canAddToBag()) {
      return this.locale.t('product.addToBag');
    }
    if (this.variants().length > 0 && !this.selectedVariant()) {
      return this.locale.t('product.selectVariant');
    }
    return this.locale.t('product.variantUnavailable');
  });

  constructor() {
    this.route.paramMap.subscribe((params) => {
      const id = Number(params.get('id') ?? 0);
      this.productId.set(Number.isFinite(id) && id > 0 ? id : null);
      this.selectedVariantSkuState.set(null);
      this.activeImageState.set(null);
      this.loading.set(false);

      if (!this.catalog.findById(id) && this.catalog.allProducts().length === 0) {
        this.catalog.reload().subscribe({
          next: () => this.loading.set(false),
          error: () => this.loading.set(false),
        });
      }
    });

    effect(() => {
      const images = this.galleryImages();
      this.activeImageState.set(images[0] ?? null);
    });
  }

  protected goBack(): void {
    if (window.history.length > 1) {
      this.location.back();
      return;
    }
    this.router.navigate(['/shop']);
  }

  protected openProduct(id: number): void {
    this.router.navigate(['/products', id]);
  }

  protected imageClasses(gradient: string): string {
    return `detail-image ${gradient}`;
  }

  protected selectImage(image: string): void {
    this.activeImageState.set(image);
  }

  protected selectVariant(variant: ProductVariant): void {
    this.selectedVariantSkuState.set(variant.sku);
  }

  protected clearVariantSelection(): void {
    this.selectedVariantSkuState.set(null);
  }

  protected addToBag(): void {
    const product = this.product();
    if (!product) {
      return;
    }

    if (product.customMade) {
      this.requestCustomOrder();
      return;
    }

    const selectedVariant = this.selectedVariant();
    const productToCart = this.decorateSelectedProduct(product, selectedVariant);
    this.cart.add(productToCart);
    const added = this.locale.t('product.added');
    this.toast.show(
      selectedVariant
        ? `${product.name} (${selectedVariant.name}) ${added}`
        : `${product.name} ${added}`,
    );
  }

  protected requestCustomOrder(): void {
    const product = this.product();
    if (!product) {
      return;
    }
    this.router.navigate(['/custom-order'], { queryParams: { productId: product.id } });
  }

  private decorateSelectedProduct(product: Product, selectedVariant: ProductVariant | null): Product {
    if (!selectedVariant) {
      return {
        ...product,
        selectedVariantSku: null,
        selectedVariantName: null,
      };
    }

    return {
      ...product,
      price:
        selectedVariant.price !== null &&
        selectedVariant.price !== undefined &&
        selectedVariant.price > 0
          ? selectedVariant.price
          : product.price + (selectedVariant.priceDelta ?? 0),
      originalPrice:
        product.originalPrice === null
          ? null
          : product.originalPrice + (selectedVariant.priceDelta ?? 0),
      image: selectedVariant.image?.trim() || product.image,
      gallery:
        selectedVariant.gallery && selectedVariant.gallery.length > 0
          ? selectedVariant.gallery
          : product.gallery,
      selectedVariantSku: selectedVariant.sku,
      selectedVariantName: selectedVariant.name,
    };
  }

  private labelize(value: string): string {
    return value
      .replace(/([A-Z])/g, ' $1')
      .replace(/[-_]+/g, ' ')
      .replace(/^\w/, (char) => char.toUpperCase())
      .trim();
  }
}
